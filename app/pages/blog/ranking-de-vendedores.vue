    <h2 id="recorte">1. O recorte: com quem o vendedor compete</h2>
    <p>
      Um ranking só motiva quando a pessoa acredita que pode subir. Vendedor de loja de rua
      competindo com vendedor de loja de shopping sabe, no dia 3, que não vai chegar ao topo. O
      recorte define quem compete com quem.
    </p>
    <ul>
      <li><strong>Por loja.</strong> Todos têm o mesmo fluxo de clientes. É o recorte mais justo para varejo.</li>
      <li><strong>Por grupo de lojas.</strong> Lojas com fluxo parecido competem entre si. Serve para redes com formatos diferentes.</li>
      <li><strong>Por tempo de casa.</strong> Vendedores com menos de seis meses competem entre si. Protege quem está começando.</li>
      <li><strong>Por rede.</strong> Reconhece os melhores da empresa. Funciona como ranking secundário.</li>
    </ul>
    <p>
      O padrão que funciona: ranking principal por loja, ranking secundário por rede. O vendedor
      disputa com quem está ao lado dele e vê onde está em relação à empresa.
    </p>

    <h2 id="metrica">2. A métrica: o que sobe e desce na lista</h2>
    <p>
      Ranking por faturamento premia quem atende o cliente que já entrou decidido. Ranking por
      percentual da meta premia quem se superou. As duas métricas contam histórias diferentes.
    </p>
    <div class="r-table">
      <table>
        <thead>
          <tr><th>Métrica</th><th>Quem lidera</th><th>Efeito no time</th></tr>
        </thead>
        <tbody>
          <tr><td>Faturamento</td><td>Quem tem maior carteira ou melhor turno</td><td>Os mesmos três de sempre no topo</td></tr>
          <tr><td>% da meta individual</td><td>Quem mais cresceu sobre a própria base</td><td>Vendedor novo pode liderar</td></tr>
          <tr><td>Pontos de campanha</td><td>Quem executa o comportamento da campanha</td><td>Foco no produto ou na ação da vez</td></tr>
          <tr><td>Itens por venda</td><td>Quem oferece adicional</td><td>Ticket médio sobe</td></tr>
        </tbody>
      </table>
    </div>
    <p>
      Para o ranking principal, use percentual da meta individual. Ele nivela vendedores de tamanhos
      diferentes. Como definir uma meta individual justa está em
      <NuxtLink to="/blog/metas-de-vendas-por-vendedor">metas de vendas por vendedor: como definir e acompanhar</NuxtLink>.
    </p>

    <h2 id="faixas">3. Faixas em vez de pódio</h2>
    <p>
      Um pódio premia três pessoas. Em uma loja de doze, nove sabem que não vão receber nada e param
      de olhar. Faixas premiam quem atinge um patamar, e todos podem atingir. A meta é o desempenho
      esperado, então o prêmio em dinheiro começa acima dela.
    </p>
    <ul>
      <li><strong>Faixa ouro:</strong> 120% da meta ou mais. Prêmio maior.</li>
      <li><strong>Faixa prata:</strong> de 110% até menos de 120%. Prêmio base.</li>
      <li><strong>Faixa bronze:</strong> de 100% até menos de 110%. Reconhecimento público, sem dinheiro.</li>
    </ul>
    <p>
      Todos os vendedores podem estar na faixa ouro ao mesmo tempo. O orçamento precisa prever esse
      caso. O ranking continua existindo dentro de cada faixa, para o reconhecimento, mas o prêmio
      vem da faixa.
    </p>

    <h2 id="ofensivas">4. Ofensivas: premiar a consistência</h2>
    <p>
      O ranking mede o acumulado. A ofensiva mede a sequência. Um vendedor que vende todo dia por
      sete dias seguidos ganha pontos extras, mesmo que o total dele seja menor do que o de quem
      vendeu tudo no sábado.
    </p>
    <p>
      A ofensiva é a mecânica que mais muda o ritmo de uma loja. Ela transforma "vou compensar no
      fim de semana" em "preciso vender hoje para não perder a sequência". Ela também dá a quem está
      no fim do ranking uma vitória possível ainda esta semana.
    </p>

    <h2 id="frequencia">5. Frequência: o placar muda no mesmo dia</h2>
    <p>
      Um ranking atualizado na segunda-feira conta o que aconteceu na semana passada. O vendedor
      não pode mais fazer nada sobre isso. Um ranking atualizado a cada venda diz o que fazer no
      próximo atendimento.
    </p>
    <p>
      Sem ferramenta, o mínimo é uma atualização por dia, em horário fixo, com a foto no grupo. Com
      ferramenta, a posição muda quando a venda entra no sistema. Um caso real: a Braduca passou a
      acompanhar o ranking diariamente no meio de uma campanha. O time emendou sete dias seguidos
      de venda e o produto da campanha cresceu 32%.
    </p>

    <h2 id="erros">Quatro erros que matam o ranking</h2>
    <ol>
      <li>
        <strong>Expor quem está no fim.</strong> O último lugar em letras grandes no quadro da loja
        humilha. Mostre o topo em público e a posição individual em privado.
      </li>
      <li>
        <strong>Mudar a regra no meio.</strong> Se a métrica muda no dia 15, o ranking perde a
        credibilidade até o fim do ano. Regra nova só na campanha seguinte.
      </li>
      <li>
        <strong>Ranking sem prêmio e sem fim.</strong> Um ranking perpétuo vira paisagem. Ele
        precisa de período, fechamento e reconhecimento.
      </li>
      <li>
        <strong>Contar venda que ainda não é venda.</strong> Pedido sem pagamento ou nota não
        emitida entra no ranking e some na apuração. A disputa vira briga.
      </li>
    </ol>

    <h2 id="modelo">Modelo de ranking para copiar</h2>
    <div class="r-box">
      <p class="r-box__label">Ranking mensal por loja</p>
      <ul>
        <li><strong>Recorte:</strong> vendedores da mesma loja. Ranking de rede só para reconhecimento.</li>
        <li><strong>Métrica:</strong> percentual da meta individual, com venda faturada.</li>
        <li><strong>Faixas:</strong> bronze a partir de 100% (reconhecimento), prata a partir de 110%, ouro a partir de 120%.</li>
        <li><strong>Ofensiva:</strong> cinco dias seguidos com venda valem um reconhecimento semanal no grupo da loja. Não altera a faixa.</li>
        <li><strong>Atualização:</strong> a cada venda, ou uma vez por dia às 18h.</li>
        <li><strong>Visibilidade:</strong> top 3 no grupo da loja. Posição completa só no app ou no extrato individual.</li>
        <li><strong>Fechamento:</strong> dia 1 do mês seguinte, com prêmio pago até o dia 10.</li>
      </ul>
    </div>
