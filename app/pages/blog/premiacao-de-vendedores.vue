    <h2 id="premio-ou-comissao">Prêmio, comissão e bônus: o que muda</h2>
    <p>
      Os três pagam o vendedor por resultado. A diferença está na natureza do pagamento: o que ele
      remunera e em que condição é pago. A folha só registra essa natureza.
    </p>
    <div class="r-table">
      <table>
        <thead>
          <tr><th>Modelo</th><th>O que é</th><th>Na folha</th><th>Quando usar</th></tr>
        </thead>
        <tbody>
          <tr>
            <td>Comissão</td>
            <td>Percentual sobre a venda, pago todo mês</td>
            <td>Integra o salário. Gera reflexos em férias, 13º, FGTS e INSS</td>
            <td>Remuneração base variável do vendedor</td>
          </tr>
          <tr>
            <td>Prêmio</td>
            <td>Liberalidade por desempenho superior ao esperado</td>
            <td>Não integra o salário, mesmo quando habitual, pelo art. 457, §2º e §4º da CLT</td>
            <td>Campanhas com objetivo, prazo e meta definidos</td>
          </tr>
          <tr>
            <td>Bônus</td>
            <td>Valor por resultado da empresa ou da área</td>
            <td>Depende de como é pago. Um valor fixo pelo trabalho normal tende a ser salário</td>
            <td>Resultado coletivo, anual ou semestral</td>
          </tr>
        </tbody>
      </table>
    </div>
    <p>
      O §4º do art. 457 da CLT, na redação da Reforma Trabalhista de 2017, define prêmio como a
      liberalidade que o empregador concede, em bens, serviços ou dinheiro, a um empregado ou grupo,
      em razão de desempenho superior ao ordinariamente esperado. O §2º diz que o prêmio não
      integra a remuneração, ainda que habitual. Dois pontos seguem daí. O prêmio recompensa o que
      passa do trabalho normal, então a meta ordinária precisa estar definida para que o "acima"
      exista. E o prêmio é uma liberalidade, então a empresa decide se e quanto paga, e o
      regulamento documenta essa decisão. Um pagamento que remunera o trabalho comum, sem referência
      de desempenho, tem outra natureza. Valide o desenho com a contabilidade ou com um advogado
      trabalhista antes da primeira campanha.
    </p>

    <h2 id="criterios">Quatro critérios de uma premiação que o time entende</h2>
    <ol>
      <li>
        <strong>Um número por objetivo.</strong> "Vender 40 unidades" é critério. "Vender bem" não
        é. O vendedor precisa calcular sozinho se está perto do prêmio.
      </li>
      <li>
        <strong>Referência acima do esperado.</strong> A meta mensal é o desempenho ordinário. O prêmio
        começa acima dela. Se a premiação paga por atingir a meta comum, o prêmio vira parte do
        salário na cabeça do time e perde o efeito.
      </li>
      <li>
        <strong>Alcançável por parte do time.</strong> Uma premiação que só o melhor vendedor bate
        motiva uma pessoa. Uma faixa que metade do time alcança motiva metade do time. Use faixas.
      </li>
      <li>
        <strong>Elegibilidade escrita.</strong> Quem participa, desde quando, e o que desclassifica.
        Venda cancelada, devolução, falta injustificada. Tudo antes de começar.
      </li>
    </ol>

    <h2 id="valor">Como definir o valor do prêmio</h2>
    <p>
      O valor do prêmio nasce da margem extra que a campanha gera. Calcule o ganho esperado e
      destine uma parte dele à premiação.
    </p>
    <div class="r-box">
      <p class="r-box__label">Exemplo de cálculo</p>
      <p>
        Uma loja vende 200 unidades de um produto por mês, com margem de R$ 60 por unidade. A
        campanha mira 280 unidades. O ganho extra esperado é de 80 × R$ 60 = R$ 4.800. A empresa
        destina 30% desse ganho à premiação: R$ 1.440. Com 6 vendedores, isso permite uma faixa 1 de R$ 120 e uma faixa 2 de R$ 240 por pessoa. Só a
        maior faixa alcançada é paga, então o teto é de R$ 1.440 se todos baterem a faixa 2.
      </p>
    </div>
    <p>
      Se o teto passar do ganho extra, a campanha dá prejuízo mesmo quando dá certo. Se o prêmio for
      pequeno demais em relação ao salário do vendedor, ninguém muda de comportamento. Como ponto de partida, e não como regra, muitos gestores testam uma faixa principal entre 10% e
      20% da remuneração mensal do vendedor. O número certo aparece na segunda campanha, quando dá
      para comparar o comportamento do time com o da primeira.
    </p>

    <h2 id="apuracao">Apuração e pagamento</h2>
    <p>
      A apuração é onde a premiação ganha ou perde a confiança do time. Três regras:
    </p>
    <ul>
      <li>A única fonte é o relatório do sistema de vendas.</li>
      <li>Cada vendedor vê o próprio extrato: o que contou, o que não contou e por quê.</li>
      <li>A apuração fecha em uma data escrita. Devoluções depois dessa data não alteram o resultado.</li>
    </ul>
    <p>
      O pagamento sai na data do regulamento, discriminado na folha como prêmio, separado da
      comissão. Pagar junto com o salário do mês seguinte é o padrão. Pagar em cartão ou vale é
      possível, desde que o regulamento diga isso antes. Se o prêmio sai com atraso ou com valor
      diferente do prometido, a campanha seguinte paga por esse erro.
    </p>

    <h2 id="modelos">Três modelos de premiação para adaptar</h2>
    <h3>Modelo 1: faixas por meta individual</h3>
    <p>
      Serve para lojas com vendedores de níveis diferentes. Cada vendedor tem a própria meta, com
      base no histórico. A meta é o desempenho esperado. As faixas premiam o que passa dela.
    </p>
    <ul>
      <li>A partir de 105% da meta: R$ 100.</li>
      <li>A partir de 115% da meta: R$ 250.</li>
      <li>A partir de 125% da meta: R$ 450.</li>
    </ul>
    <p>
      Quem está em 95% no dia 20 ainda tem um alvo. Quem passou dos 105% continua vendendo até os
      125%. Só a maior faixa alcançada é paga.
      Como calcular a meta de cada um está em
      <NuxtLink to="/blog/metas-de-vendas-por-vendedor">metas de vendas por vendedor: como definir e acompanhar</NuxtLink>.
    </p>

    <h3>Modelo 2: pontos por produto com ofensiva</h3>
    <p>
      Serve para lançamentos e giro de estoque. Cada unidade vale pontos. A referência de desempenho esperado é a venda média do produto no
      mês anterior, convertida em pontos: no exemplo abaixo, 200 pontos. As faixas de prêmio ficam
      acima dela, e só a maior faixa alcançada é paga. Vender todo dia por cinco dias seguidos vale
      um bônus de pontos, que só conta depois que o vendedor passa da referência.
    </p>
    <ul>
      <li>Referência esperada: 200 pontos, a média do mês anterior.</li>
      <li>10 pontos por unidade. 3 pontos extras por item adicional na mesma venda.</li>
      <li>Ofensiva de 5 dias: +50 pontos, contados só acima da referência.</li>
      <li>A partir de 300 pontos: R$ 150. A partir de 500 pontos: R$ 350.</li>
    </ul>

    <h3>Modelo 3: meta de equipe com ranking interno</h3>
    <p>
      Serve para lojas onde a venda é compartilhada, como móveis ou materiais de construção. A loja tem uma meta coletiva, que é o desempenho esperado. Se a loja chega a 105% da meta,
      todos recebem a faixa base. O ranking interno define um adicional para os três primeiros.
    </p>
    <ul>
      <li>Loja em 105% da meta ou mais: R$ 120 para cada vendedor ativo no período.</li>
      <li>Top 3 da loja, entre quem passou da própria meta: R$ 300, R$ 200 e R$ 100 adicionais.</li>
      <li>Loja fica abaixo de 105%: ninguém recebe. Regra escrita e conhecida antes.</li>
    </ul>
    <p>
      Os três modelos usam a mesma estrutura: número, faixa, elegibilidade, data. Escolha um,
