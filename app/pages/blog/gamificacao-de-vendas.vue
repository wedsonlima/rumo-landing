    <h2 id="o-que-e">O que é gamificação de vendas</h2>
    <p>
      Gamificação de vendas é o uso de mecânicas de jogo para orientar o comportamento diário do time
      comercial. As mecânicas mais comuns são pontos, ranking, missões, sequências e prêmios. A meta
      continua a mesma. O que muda é a forma como o vendedor enxerga o caminho até ela.
    </p>
    <p>
      Um jogo funciona porque tem três coisas que a maioria das campanhas de vendas não tem: regra
      clara, placar visível e recompensa imediata. Quando a campanha vive numa planilha que o
      supervisor atualiza na sexta-feira, o vendedor não tem placar. Sem placar, ele não muda de
      comportamento. Ele só espera o resultado.
    </p>

    <h2 id="mecanicas">Cinco mecânicas que funcionam em loja</h2>
    <p>
      Nem toda mecânica de jogo serve para vendas. As cinco abaixo têm um comportamento claro por
      trás e cabem em uma operação de varejo com vários vendedores por loja.
    </p>
    <ol>
      <li>
        <strong>Pontos por ação.</strong> Cada venda, item adicional ou cadastro de cliente vale um
        número. O vendedor sabe quanto acabou de ganhar. O ponto conecta a ação de agora ao prêmio de
        depois.
      </li>
      <li>
        <strong>Ranking por loja e por rede.</strong> Todos veem quem lidera, quem está no meio e
        quem precisa reagir. O ranking por loja mantém a disputa justa entre quem tem o mesmo fluxo
        de clientes. O ranking por rede reconhece os melhores da empresa.
      </li>
      <li>
        <strong>Ofensiva de dias seguidos.</strong> Vender todo dia por sete dias vale mais do que
        vender tudo na última semana. A ofensiva premia a consistência. Ela é a mecânica que mais
        muda o ritmo de uma loja.
      </li>
      <li>
        <strong>Missão por produto.</strong> Uma meta curta, de dois ou três dias, para um produto
        específico. Serve para girar estoque parado ou lançar uma linha nova. A missão tem começo,
        fim e prêmio próprio.
      </li>
      <li>
        <strong>Faixas de premiação.</strong> Em vez de um único prêmio, três faixas acima da meta:
        105%, 115% e 125%. Quem está em 95% no dia 20 ainda tem um alvo alcançável. Quem já passou
        da primeira faixa continua vendendo.
      </li>
    </ol>

    <h2 id="exemplo">Exemplo: uma rede de calçados com seis lojas</h2>
    <p>
      Imagine uma rede com seis lojas e 34 vendedores. O objetivo do mês é vender uma linha nova de
      tênis. O gestor monta uma campanha de três semanas com as regras abaixo.
    </p>
    <div class="r-table">
      <table>
        <thead>
          <tr><th>Regra</th><th>Valor</th><th>Comportamento esperado</th></tr>
        </thead>
        <tbody>
          <tr><td>Referência esperada</td><td>200 pontos</td><td>Venda média da linha anterior no mesmo período. O prêmio começa acima dela</td></tr>
          <tr><td>Ponto por par vendido</td><td>10 pontos</td><td>Oferecer a linha nova a cada atendimento</td></tr>
          <tr><td>Bônus por meia ou palmilha junto</td><td>+3 pontos</td><td>Aumentar o ticket médio</td></tr>
          <tr><td>Ofensiva de 5 dias seguidos, uma por semana</td><td>+50 pontos, contados só acima da referência</td><td>Vender todo dia, sem depender do sábado</td></tr>
          <tr><td>Faixa 1: a partir de 300 pontos</td><td>R$ 150</td><td>Alvo para quem começa devagar</td></tr>
          <tr><td>Faixa 2: a partir de 500 pontos</td><td>R$ 350</td><td>Alvo principal</td></tr>
          <tr><td>Top 3 da rede, entre quem passou da faixa 1</td><td>R$ 600</td><td>Reconhecer os melhores</td></tr>
        </tbody>
      </table>
    </div>
    <p>
      Só a maior faixa alcançada é paga e o top 3 é um adicional. Com 34 vendedores, o orçamento
      máximo da campanha é conhecido antes de começar: se todos baterem a faixa 2, o custo é de R$
      11.900 mais R$ 1.800 do top 3. Na prática, uma parte do
      time fica na faixa 1 e outra parte não chega a nenhuma. O gestor define o orçamento com esse
      teto em mente e ajusta o valor do ponto para caber nele.
    </p>
    <p>
      O que muda no dia a dia: o vendedor abre o app de manhã e vê que está com 180 pontos, que a
      colega da loja do lado está com 240, e que faltam dois dias para completar a ofensiva. Ele
      oferece o tênis no primeiro atendimento. Sem a campanha, ele oferecia o que o cliente pedia.
    </p>

    <h2 id="erros">Três erros que transformam o jogo em ruído</h2>
    <p>
      Gamificação mal feita é pior do que nenhuma gamificação. O time percebe quando a regra é
      confusa ou quando o prêmio não chega. Os três erros abaixo aparecem em quase toda primeira
      tentativa.
    </p>
    <ul>
      <li>
        Um ranking único para a rede inteira. A loja de shopping sempre vence a loja de rua e, em
        duas semanas, metade do time para de olhar. Use ranking por loja, ou por grupo de lojas com
        fluxo parecido.
      </li>
      <li>
        Um placar atualizado uma vez por semana. Se o vendedor só vê o resultado na segunda-feira,
        a campanha vira um relatório. O placar precisa mudar no mesmo dia da venda.
      </li>
      <li>
        Um prêmio pago com atraso. A campanha fecha no dia 30 e o prêmio cai no dia 20 do mês
        seguinte, ou nem cai. Na campanha seguinte, ninguém joga. A data de pagamento é parte da
        regra.
      </li>
    </ul>

    <h2 id="como-comecar">Como montar a primeira campanha em duas semanas</h2>
    <p>
      Uma campanha curta serve para testar a mecânica e conquistar a confiança do time. Siga a
      sequência abaixo.
    </p>
    <ol>
      <li>Escolha um único objetivo: um produto, uma categoria ou o ticket médio.</li>
      <li>Defina uma métrica por ponto. Uma só. Duas métricas na primeira campanha confundem.</li>
      <li>Crie duas faixas de prêmio: uma alcançável por metade do time e outra para os melhores.</li>
      <li>Defina o orçamento máximo, considerando todos batendo a faixa mais alta.</li>
      <li>Escreva a regra em uma página e mostre ao time antes de começar.</li>
      <li>Publique o placar todo dia. Se não houver ferramenta, mande uma foto no grupo às 18h.</li>
      <li>Pague o prêmio na data combinada, sem exceção.</li>
    </ol>
    <p>
      Depois da primeira campanha, o time sabe que a regra vale e que o prêmio chega. A partir daí, o
      gestor pode ampliar: mais métricas, ofensivas, missões por produto. Para montar a estrutura
